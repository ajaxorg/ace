"use strict";

/**
 * Trusted Types support. A page whose Content-Security-Policy includes
 * `require-trusted-types-for 'script'` refuses plain strings at HTML and script URL sinks
 * (innerHTML, script src, new Worker), so Ace passes the markup it generates itself and the
 * URLs of its own scripts and workers through an "ace" policy. HTML that an app hands to Ace
 * (tooltip.setHtml, a completion's docHTML, a line widget's html) is not passed through it:
 * apps that enforce Trusted Types pass TrustedHTML there, which innerHTML accepts as it is.
 *
 * Without Trusted Types support in the browser, or when the page's `trusted-types` directive
 * doesn't allow the "ace" name, the strings are returned unchanged.
 */

/**@type {any}*/
var policy;

function getPolicy() {
    if (policy === undefined) {
        policy = null;
        var trustedTypes = typeof window == "object" && /**@type {any}*/(window).trustedTypes;
        if (trustedTypes) {
            try {
                policy = trustedTypes.createPolicy("ace", {
                    createHTML: function(html) { return html; },
                    createScriptURL: function(url) { return url; }
                });
            } catch (e) {
                // the page's trusted-types directive doesn't allow the name
            }
        }
    }
    return policy;
}

/**
 * @param {string} html markup generated by Ace
 * @returns {any} TrustedHTML, or the string when Trusted Types isn't available
 */
exports.createHTML = function(html) {
    var p = getPolicy();
    return p ? p.createHTML(html) : html;
};

/**
 * @param {string} url the URL of one of Ace's own scripts or workers
 * @returns {any} TrustedScriptURL, or the string when Trusted Types isn't available
 */
exports.createScriptURL = function(url) {
    var p = getPolicy();
    return p ? p.createScriptURL(url) : url;
};

/** forgets the policy so the next call looks for Trusted Types again (used by tests) */
exports.$resetPolicy = function() {
    policy = undefined;
};
